// Waiting for one frame's DMA; far longer than a 4K frame takes.
constexpr uint64_t kDmaTimeoutNs = 200'000'000;

// dvpInitGLContext once per GL context, shared by the inputs captured in that context.
std::mutex g_dvpContextMutex;
std::map<HGLRC, int> g_dvpContexts;

bool acquireDvpContext() {
    std::lock_guard<std::mutex> lock(g_dvpContextMutex);
    int& users = g_dvpContexts[wglGetCurrentContext()];
    if (users == 0 && dvpInitGLContext(DVP_DEVICE_FLAGS_SHARE_APP_CONTEXT) != DVP_STATUS_OK) {
        g_dvpContexts.erase(wglGetCurrentContext());
        return false;
    }
    ++users;
    return true;
}

void releaseDvpContext() {
    std::lock_guard<std::mutex> lock(g_dvpContextMutex);
    auto it = g_dvpContexts.find(wglGetCurrentContext());
    if (it != g_dvpContexts.end() && --it->second == 0) {
        dvpCloseGLContext();
        g_dvpContexts.erase(it);
    }
}

// Semaphore shared by the CPU and GPU to synchronise access to a DVP buffer.
struct DvpSync {
    uint32_t* sem = nullptr;
    uint32_t releaseValue = 0;
    uint32_t acquireValue = 0;
    DVPSyncObjectHandle handle = 0;

    bool create(uint32_t allocSize, uint32_t alignment) {
        sem = static_cast<uint32_t*>(_aligned_malloc(std::max<uint32_t>(allocSize, sizeof(uint32_t)), std::max<uint32_t>(alignment, 4)));
        if (!sem)
            return false;
        sem[0] = 0;
        DVPSyncObjectDesc desc{};
        desc.sem = sem;
        return dvpImportSyncObject(&desc, &handle) == DVP_STATUS_OK;
    }
    ~DvpSync() {
        if (handle)
            dvpFreeSyncObject(handle);
        if (sem)
            _aligned_free(sem);
    }
};

// VirtualLock is limited by the working set minimum: grow it for the pinned buffers.
bool lockMemory(void* memory, size_t size) {
    if (VirtualLock(memory, size))
        return true;
    SIZE_T minSize = 0;
    SIZE_T maxSize = 0;
    const HANDLE process = GetCurrentProcess();
    if (!GetProcessWorkingSetSize(process, &minSize, &maxSize)
        || !SetProcessWorkingSetSize(process, minSize + size * 4, std::max(maxSize, minSize + size * 4) + size * 4))
        return false;
    return VirtualLock(memory, size) != FALSE;
}
