BlackmagicAudioCapture::BlackmagicAudioCapture(int input)
    : m_input(input) {
    m_fifo.assign(kAudioFifoCapacity * 2, 0.f);
    m_lastKeepAlive = std::chrono::steady_clock::now();
    m_thread = std::thread([this] { run(); });
}

BlackmagicAudioCapture::~BlackmagicAudioCapture() {
    {
        std::lock_guard<std::mutex> lock(m_mutex);
        m_terminate = true;
    }
    m_cv.notify_all();
    if (m_thread.joinable())
        m_thread.join();
}

void BlackmagicAudioCapture::keepAlive(float volume, bool reportLevels) {
    m_volume.store(std::clamp(volume, 0.f, 1.f));
    m_reportLevels.store(reportLevels);
    bool wake = false;
    {
        std::lock_guard<std::mutex> lock(m_mutex);
        m_lastKeepAlive = std::chrono::steady_clock::now();
        wake = !m_running.load();
    }
    if (wake)
        m_cv.notify_all();
}

void BlackmagicAudioCapture::setMixToOutput(bool mix) {
    if (m_mixToOutput.exchange(mix) != mix && m_running.load())
        restart();
}

void BlackmagicAudioCapture::restart() {
    {
        std::lock_guard<std::mutex> lock(m_mutex);
        m_restart = true;
    }
    m_cv.notify_all();
}

float BlackmagicAudioCapture::takePeak() {
    return m_peak.exchange(-1.f);
}

void BlackmagicAudioCapture::run() {
    auto nextAttempt = std::chrono::steady_clock::now();
    std::unique_lock<std::mutex> lock(m_mutex);
    while (!m_terminate) {
        m_cv.wait_for(lock, std::chrono::milliseconds(200));
        if (m_terminate)
            break;

        const auto now = std::chrono::steady_clock::now();
        const bool wanted = now - m_lastKeepAlive < kAudioKeepAliveTimeout;
        const bool restart = std::exchange(m_restart, false);

        lock.unlock();
        if (m_running.load() && (!wanted || restart))
            close();
        if (wanted && !m_running.load() && (restart || now >= nextAttempt)) {
            if (!open())
                nextAttempt = now + kRetryInterval;
        }
        lock.lock();
    }
    lock.unlock();

    close();
    if (m_paInitialized)
        cplay::audio::paTerminate();
}

bool BlackmagicAudioCapture::open() {
    const auto fail = [this](const std::string& msg) {
        if (msg != m_lastLoggedError) {
            m_lastLoggedError = msg;
            sgct::Log::Warning("CaptureLayer: " + msg);
        }
        close();
        return false;
    };

    if (!m_paInitialized) {
        const PaError paErr = cplay::audio::paInitialize();
        if (paErr != paNoError)
            return fail(std::format("PortAudio initialization failed ({})", Pa_GetErrorText(paErr)));
        m_paInitialized = true;
    }

    PaStreamParameters params{};
    params.device = chooseOutputDevice();
    const PaDeviceInfo* device = params.device != paNoDevice ? Pa_GetDeviceInfo(params.device) : nullptr;
    if (!device)
        return fail("no audio output device for capture audio");
    m_outChannels = 2;
    if (m_mixToOutput.load())
        m_outChannels = std::max(1, cplay::audio::configuredOutputChannels(device->maxOutputChannels));
    params.channelCount = m_outChannels;
    params.sampleFormat = paFloat32;
    params.suggestedLatency = device->defaultLowOutputLatency;

    clearFifo();
    PaStream* stream = nullptr;
    PaError paErr = cplay::audio::paOpenStream(&stream, nullptr, &params, kAudioSampleRate, kAudioFramesPerBuffer,
                                               paClipOff, audioOutputCallback, this);
    if (paErr == paNoError) {
        m_stream = stream;
        m_running.store(true);
        paErr = cplay::audio::paStartStream(stream);
    }
    if (paErr != paNoError)
        return fail(std::format("could not open the audio output for Blackmagic input {} ({})", m_input, Pa_GetErrorText(paErr)));

    m_lastLoggedError.clear();
    sgct::Log::Info(std::format("CaptureLayer: Blackmagic input {} audio 48000 Hz stereo -> '{}' ({} ch)", m_input,
                                device->name, m_outChannels));
    return true;
}

void BlackmagicAudioCapture::close() {
    m_running.store(false);
    if (m_stream) {
        PaStream* stream = static_cast<PaStream*>(m_stream);
        if (cplay::audio::paStopStream(stream) != paNoError)
            cplay::audio::paAbortStream(stream);
        cplay::audio::paCloseStream(stream);
        m_stream = nullptr;
    }
    clearFifo();
}

void BlackmagicAudioCapture::clearFifo() {
    std::lock_guard<std::mutex> lock(m_fifoMutex);
    m_fifoRead = 0;
    m_fifoFrames = 0;
    m_fifoPrimed = false;
}

void BlackmagicAudioCapture::push(const int32_t* samples, unsigned long frames) {
    if (!m_running.load())
        return;
    std::lock_guard<std::mutex> lock(m_fifoMutex);
    for (unsigned long f = 0; f < frames; ++f) {
        if (m_fifoFrames == kAudioFifoCapacity) {
            m_fifoRead = (m_fifoRead + 1) % kAudioFifoCapacity;
            --m_fifoFrames;
        }
        const size_t write = (m_fifoRead + m_fifoFrames) % kAudioFifoCapacity;
        m_fifo[write * 2] = static_cast<float>(samples[f * 2]) / 2147483648.f;
        m_fifo[write * 2 + 1] = static_cast<float>(samples[f * 2 + 1]) / 2147483648.f;
        ++m_fifoFrames;
    }
    // The capture runs ahead of the output clock: drop the oldest samples to bound the latency.
    if (m_fifoFrames > kAudioMaxFrames) {
        const size_t drop = m_fifoFrames - kAudioPrimeFrames;
        m_fifoRead = (m_fifoRead + drop) % kAudioFifoCapacity;
        m_fifoFrames -= drop;
    }
}

void BlackmagicAudioCapture::fillOutput(float* out, unsigned long frames) {
    const float volume = m_volume.load();
    float peak = 0.f;
    // Copy in chunks into a stack buffer, then map stereo onto the output layout.
    constexpr unsigned long kChunk = 256;
    float stereo[kChunk * 2];
    for (unsigned long first = 0; first < frames; first += kChunk) {
        const unsigned long n = std::min(kChunk, frames - first);
        unsigned long available = 0;
        {
            std::lock_guard<std::mutex> lock(m_fifoMutex);
            if (!m_fifoPrimed && m_fifoFrames >= kAudioPrimeFrames)
                m_fifoPrimed = true;
            if (m_fifoPrimed) {
                available = static_cast<unsigned long>(std::min<size_t>(n, m_fifoFrames));
                for (unsigned long f = 0; f < available; ++f) {
                    const size_t read = (m_fifoRead + f) % kAudioFifoCapacity;
                    stereo[f * 2] = m_fifo[read * 2];
                    stereo[f * 2 + 1] = m_fifo[read * 2 + 1];
                }
                m_fifoRead = (m_fifoRead + available) % kAudioFifoCapacity;
                m_fifoFrames -= available;
                if (available < n)
                    m_fifoPrimed = false; // ran dry: wait until primed again
            }
        }
        for (unsigned long i = 0; i < available * 2; ++i) {
            stereo[i] *= volume;
            peak = std::max(peak, std::fabs(stereo[i]));
        }
        std::fill(stereo + available * 2, stereo + n * 2, 0.f);
        m_mixer.processInterleaved(stereo, 2, out + static_cast<size_t>(first) * m_outChannels, m_outChannels, n);
    }

    if (m_reportLevels.load()) {
        float previous = m_peak.load();
        while (peak > previous && !m_peak.compare_exchange_weak(previous, peak)) {
        }
    }
}
