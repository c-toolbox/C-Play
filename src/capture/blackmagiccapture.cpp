std::vector<CaptureInputInfo> BlackmagicCaptureBackend::listInputs() {
    std::vector<CaptureInputInfo> inputs;
    ScopedCom com;
    forEachCaptureDevice([&inputs](int input, IDeckLink* device) {
        CaptureInputInfo info;
        info.source.backend = "blackmagic";
        info.source.input = input;

        std::string mode = "no signal";
        const DetectedSignal signal = detectSignal(device);
        IDeckLinkInput* deckLinkInput = nullptr;
        IDeckLinkDisplayMode* displayMode = nullptr;
        if (signal.locked && device->QueryInterface(IID_IDeckLinkInput, reinterpret_cast<void**>(&deckLinkInput)) == S_OK
            && deckLinkInput->GetDisplayMode(signal.mode, &displayMode) == S_OK && displayMode) {
            info.width = static_cast<int>(displayMode->GetWidth());
            info.height = static_cast<int>(displayMode->GetHeight());
            BMDTimeValue duration = 0;
            BMDTimeScale scale = 0;
            mode = std::format("{}x{}", info.width, info.height);
            if (displayMode->GetFrameRate(&duration, &scale) == S_OK && duration > 0)
                mode += std::format("@{:.4g}Hz", static_cast<double>(scale) / static_cast<double>(duration));
        }
        safeRelease(displayMode);
        safeRelease(deckLinkInput);

        const std::string name = deviceName(device);
        info.name = std::format("Blackmagic {}: {} ({})", input, name.empty() ? "DeckLink input" : name, mode);
        inputs.push_back(std::move(info));
        return true;
    });
    return inputs;
}

void BlackmagicCaptureBackend::onFormatChanged(uint32_t displayMode, bool rgb) {
    if (!m_callbacksEnabled.load())
        return;
    std::lock_guard<std::mutex> lock(m_formatMutex);
    m_formatChanged = true;
    m_pendingMode = displayMode;
    m_pendingRgb = rgb;
}

void BlackmagicCaptureBackend::onFrameArrived(IDeckLinkVideoInputFrame* videoFrame, IDeckLinkAudioInputPacket* audioPacket) {
    if (!m_callbacksEnabled.load())
        return;

    if (audioPacket) {
        std::lock_guard<std::mutex> lock(m_audioMutex);
        void* samples = nullptr;
        if (m_audio && audioPacket->GetBytes(&samples) == S_OK && samples)
            m_audio->push(static_cast<const int32_t*>(samples), static_cast<unsigned long>(audioPacket->GetSampleFrameCount()));
    }

    if (!videoFrame)
        return;
    if (videoFrame->GetFlags() & bmdFrameHasNoInputSource) {
        m_hasSignal.store(false);
        return;
    }
    m_hasSignal.store(true);

    // Only the newest frame is kept: a frame the renderer has not picked up yet goes back to the driver.
    videoFrame->AddRef();
    IDeckLinkVideoInputFrame* previous = nullptr;
    {
        std::lock_guard<std::mutex> lock(m_frameMutex);
        previous = std::exchange(m_pendingFrame, videoFrame);
    }
    if (previous)
        previous->Release();
}

void BlackmagicCaptureBackend::update() {
    const auto now = std::chrono::steady_clock::now();
    const auto report = [this](const std::string& msg, bool isError) {
        if (isError)
            setError(msg);
        if (msg != m_lastLoggedError) {
            m_lastLoggedError = msg;
            if (isError)
                sgct::Log::Warning(std::format("CaptureLayer: {}", msg));
            else
                sgct::Log::Info(std::format("CaptureLayer: {}", msg));
        }
    };

    if (!m_input) {
        if (now < m_nextAttempt)
            return;
        std::string message;
        switch (openCapture(message)) {
        case OpenResult::Failed:
            m_nextAttempt = now + kRetryInterval;
            report(message, true);
            return;
        case OpenResult::Waiting:
            m_nextAttempt = now + kSignalPollInterval;
            m_hasSignal.store(false);
            setError("");
            report(message, false);
            return;
        case OpenResult::Opened:
            setError("");
            m_lastLoggedError.clear();
            break;
        }
    }

    applyFormatChange();
    if (m_directGpu)
        m_directGpu->releaseRetired(false);
    consumeFrame();
}

BlackmagicCaptureBackend::OpenResult BlackmagicCaptureBackend::openCapture(std::string& message) {
    if (!m_comInitialized) {
        const HRESULT hr = CoInitializeEx(nullptr, COINIT_MULTITHREADED);
        m_comInitialized = SUCCEEDED(hr);
    }

    IDeckLink* device = nullptr;
    int count = 0;
    const bool driver = forEachCaptureDevice([&](int input, IDeckLink* d) {
        count = input;
        if (input != m_source.input)
            return true;
        device = d;
        device->AddRef();
        return false;
    });
    if (!driver) {
        message = "Blackmagic Desktop Video driver (DeckLink) is not installed on this machine";
        return OpenResult::Failed;
    }
    if (!device) {
        message = std::format("Blackmagic input {} is not available ({} capture input(s) found)", m_source.input, count);
        return OpenResult::Failed;
    }

    IDeckLinkProfileAttributes* attributes = nullptr;
    BOOL formatDetection = FALSE;
    if (device->QueryInterface(IID_IDeckLinkProfileAttributes, reinterpret_cast<void**>(&attributes)) == S_OK)
        attributes->GetFlag(BMDDeckLinkSupportsInputFormatDetection, &formatDetection);
    safeRelease(attributes);
    m_formatDetection = formatDetection != FALSE;

    // Without format detection the capture must be opened in the mode of the incoming signal.
    const DetectedSignal signal = detectSignal(device);
    if (!signal.locked && !m_formatDetection) {
        device->Release();
        message = std::format("Blackmagic input {}: waiting for a signal", m_source.input);
        return OpenResult::Waiting;
    }

    const HRESULT hr = device->QueryInterface(IID_IDeckLinkInput, reinterpret_cast<void**>(&m_input));
    device->Release();
    if (hr != S_OK || !m_input) {
        m_input = nullptr;
        message = std::format("Blackmagic input {} cannot capture (0x{:08x})", m_source.input, static_cast<unsigned long>(hr));
        return OpenResult::Failed;
    }

    // Any supported mode will do until format detection reports the real one.
    BMDDisplayMode mode = signal.mode;
    if (!signal.locked) {
        IDeckLinkDisplayModeIterator* modes = nullptr;
        IDeckLinkDisplayMode* first = nullptr;
        if (m_input->GetDisplayModeIterator(&modes) == S_OK && modes && modes->Next(&first) == S_OK && first)
            mode = first->GetDisplayMode();
        safeRelease(first);
        safeRelease(modes);
    }

    m_callback = new InputCallback(this);
    m_input->SetCallback(m_callback);
    m_callbacksEnabled.store(true);

    // GPU direct frames are converted by the compute shader, which needs OpenGL 4.3.
    m_directGpuFailed = false;
    if (m_source.directGpu && gpuConversionReady())
        m_directGpu = BlackmagicDirectGpu::create(m_source.input);

    if (!enableVideo(mode, signal.rgb, false)) {
        message = std::format("could not enable video on Blackmagic input {} (in use by another application?)", m_source.input);
        closeCapture();
        return OpenResult::Failed;
    }

    m_audioEnabled = false;
    if (m_source.audio) {
        m_audioEnabled = m_input->EnableAudioInput(bmdAudioSampleRate48kHz, bmdAudioSampleType32bitInteger, 2) == S_OK;
        if (!m_audioEnabled)
            sgct::Log::Warning(std::format("CaptureLayer: could not enable audio on Blackmagic input {}", m_source.input));
    }

    const HRESULT startResult = m_input->StartStreams();
    if (startResult != S_OK) {
        message = std::format("could not start capture on Blackmagic input {} (0x{:08x})", m_source.input,
                              static_cast<unsigned long>(startResult));
        closeCapture();
        return OpenResult::Failed;
    }

    if (!m_directGpu)
        m_transfer.store(Transfer::Cpu);
    else
        m_transfer.store(m_directGpu->kind() == BlackmagicDirectGpu::Kind::Nvidia ? Transfer::DirectGpuNvidia : Transfer::DirectGpuAmd);
    sgct::Log::Info(std::format("CaptureLayer: Blackmagic input {} capturing{}{} via {}", m_source.input,
                                signal.locked ? "" : " (waiting for a signal)",
                                m_formatDetection ? " with input format detection" : "", transferName(m_transfer.load())));
    return OpenResult::Opened;
}

bool BlackmagicCaptureBackend::enableVideo(uint32_t displayMode, bool rgb, bool restartStreams) {
    const BMDDisplayMode mode = static_cast<BMDDisplayMode>(displayMode);
    BMDPixelFormat pixelFormat = bmdFormat8BitYUV;
    if (rgb) {
        BMDDisplayMode actual = bmdModeUnknown;
        BOOL supported = FALSE;
        if (m_input->DoesSupportVideoMode(bmdVideoConnectionUnspecified, mode, bmdFormat8BitBGRA, bmdNoVideoInputConversion,
                                          bmdSupportedVideoModeDefault, &actual, &supported) == S_OK
            && supported)
            pixelFormat = bmdFormat8BitBGRA;
    }
    const BMDVideoInputFlags flags = m_formatDetection ? bmdVideoInputEnableFormatDetection : bmdVideoInputFlagDefault;

    if (restartStreams)
        m_input->PauseStreams();
    HRESULT hr = E_FAIL;
    if (m_directGpu) {
        hr = m_input->EnableVideoInputWithAllocatorProvider(mode, pixelFormat, flags, m_directGpu->provider());
        // Only possible before the first frame: once frames use the pinned buffers the provider stays.
        if (hr != S_OK && !restartStreams) {
            sgct::Log::Warning(std::format("CaptureLayer: Blackmagic input {} cannot capture into GPU direct buffers (0x{:08x}) - "
                                           "copying through system memory", m_source.input, static_cast<unsigned long>(hr)));
            m_directGpu.reset();
        }
    }
    if (!m_directGpu)
        hr = m_input->EnableVideoInput(mode, pixelFormat, flags);
    if (restartStreams) {
        m_input->FlushStreams();
        m_input->StartStreams();
    }
    if (hr != S_OK) {
        sgct::Log::Warning(std::format("CaptureLayer: Blackmagic input {} cannot capture mode 0x{:08x} (0x{:08x})",
                                       m_source.input, static_cast<unsigned long>(mode), static_cast<unsigned long>(hr)));
        return false;
    }
    m_displayMode = displayMode;
    m_rgb = pixelFormat == bmdFormat8BitBGRA;
    return true;
}

void BlackmagicCaptureBackend::applyFormatChange() {
    uint32_t mode = 0;
    bool rgb = false;
    {
        std::lock_guard<std::mutex> lock(m_formatMutex);
        if (!m_formatChanged)
            return;
        m_formatChanged = false;
        mode = m_pendingMode;
        rgb = m_pendingRgb;
    }
    if (mode == m_displayMode && rgb == m_rgb)
        return;

    releasePendingFrame();
    if (enableVideo(mode, rgb, true)) {
        IDeckLinkDisplayMode* displayMode = nullptr;
        std::string name;
        if (m_input->GetDisplayMode(static_cast<BMDDisplayMode>(mode), &displayMode) == S_OK && displayMode) {
            BSTR str = nullptr;
            if (displayMode->GetName(&str) == S_OK)
                name = bstrToUtf8(str);
            displayMode->Release();
        }
        sgct::Log::Info(std::format("CaptureLayer: Blackmagic input {} detected {} ({})", m_source.input,
                                    name.empty() ? std::format("mode 0x{:08x}", mode) : name, m_rgb ? "RGB" : "YCbCr 4:2:2"));
    }
}

void BlackmagicCaptureBackend::releasePendingFrame() {
    IDeckLinkVideoInputFrame* frame = nullptr;
    {
        std::lock_guard<std::mutex> lock(m_frameMutex);
        frame = std::exchange(m_pendingFrame, nullptr);
    }
    if (frame)
        frame->Release();
}

void BlackmagicCaptureBackend::ensureTexture(int width, int height) {
    if (m_texture != 0 && width == m_texWidth && height == m_texHeight)
        return;
    UnpackStateGuard guard;
    if (m_texture == 0)
        glGenTextures(1, &m_texture);
    glBindTexture(GL_TEXTURE_2D, m_texture);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, width, height, 0, GL_BGRA, GL_UNSIGNED_BYTE, nullptr);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_BASE_LEVEL, 0);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAX_LEVEL, 0);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    m_texWidth = width;
    m_texHeight = height;
}

void BlackmagicCaptureBackend::consumeFrame() {
    IDeckLinkVideoInputFrame* frame = nullptr;
    {
        std::lock_guard<std::mutex> lock(m_frameMutex);
        frame = std::exchange(m_pendingFrame, nullptr);
    }
    if (!frame)
        return;

    const int width = static_cast<int>(frame->GetWidth());
    const int height = static_cast<int>(frame->GetHeight());
    if (width > 0 && height > 0) {
        bool uploaded = false;
        if (m_directGpu && !m_directGpuFailed)
            uploaded = uploadDirectGpu(frame, width, height);
        if (!uploaded && frame->GetPixelFormat() == bmdFormat8BitYUV)
            uploaded = uploadGpu(frame, width, height);
        if (!uploaded)
            uploaded = uploadCpu(frame, width, height);
        if (uploaded) {
            m_textureId = m_texture;
            m_width = width;
            m_height = height;
        }
    }
    frame->Release();
}

bool BlackmagicCaptureBackend::gpuConversionReady() {
    if (m_gpuConversionFailed)
        return false;
    if (!m_gpuConversion)
        m_gpuConversion = std::make_unique<NdiGpuConversion>();
    if (!m_gpuConversion->initialize()) {
        m_gpuConversionFailed = true;
        sgct::Log::Warning(std::format("CaptureLayer: Blackmagic input {}: GPU colour conversion unavailable - converting on the CPU",
                                       m_source.input));
        return false;
    }
    return true;
}

bool BlackmagicCaptureBackend::uploadDirectGpu(IDeckLinkVideoInputFrame* frame, int width, int height) {
    const BMDPixelFormat pixelFormat = frame->GetPixelFormat();
    if (pixelFormat != bmdFormat8BitYUV && pixelFormat != bmdFormat8BitBGRA)
        return false;
    const auto rowBytes = static_cast<unsigned int>(frame->GetRowBytes());
    bool ok = gpuConversionReady() && m_directGpu->transfer(frame, static_cast<size_t>(rowBytes) * static_cast<size_t>(height));
    if (ok) {
        ensureTexture(width, height);
        // The compute shader writes the rows bottom-up.
        ok = m_gpuConversion->convert(m_texture, width, height, m_directGpu->buffer(), m_directGpu->bufferBytes(), rowBytes,
                                      pixelFormat == bmdFormat8BitYUV ? NdiGpuConversion::Format::UYVY : NdiGpuConversion::Format::BGRX);
    }
    m_directGpu->endRead();
    if (!ok) {
        // Frames keep coming in the pinned buffers; they are uploaded through system memory instead.
        m_directGpuFailed = true;
        m_transfer.store(Transfer::Cpu);
        sgct::Log::Warning(std::format("CaptureLayer: GPU direct transfer failed on Blackmagic input {} - copying through system memory",
                                       m_source.input));
        return false;
    }
    m_flipY = false;
    return true;
}

bool BlackmagicCaptureBackend::uploadGpu(IDeckLinkVideoInputFrame* frame, int width, int height) {
    if (!gpuConversionReady())
        return false;

    FrameBytes bytes(frame);
    if (!bytes.data())
        return false;
    ensureTexture(width, height);
    // The compute shader writes the rows bottom-up.
    if (!m_gpuConversion->upload(m_texture, width, height, bytes.data(), static_cast<unsigned int>(frame->GetRowBytes()),
                                 NdiGpuConversion::Format::UYVY))
        return false;
    m_flipY = false;
    return true;
}

bool BlackmagicCaptureBackend::uploadCpu(IDeckLinkVideoInputFrame* frame, int width, int height) {
    IDeckLinkVideoFrame* bgra = nullptr;
    if (frame->GetPixelFormat() == bmdFormat8BitBGRA) {
        bgra = frame;
        bgra->AddRef();
    } else {
        if (!m_converter
            && FAILED(CoCreateInstance(CLSID_CDeckLinkVideoConversion, nullptr, CLSCTX_ALL, IID_IDeckLinkVideoConversion,
                                       reinterpret_cast<void**>(&m_converter)))) {
            m_converter = nullptr;
            return false;
        }
        if (m_converter->ConvertNewFrame(frame, bmdFormat8BitBGRA, bmdColorspaceRec709, nullptr, &bgra) != S_OK || !bgra)
            return false;
    }

    bool uploaded = false;
    {
        FrameBytes bytes(bgra);
        const long rowBytes = bgra->GetRowBytes();
        if (bytes.data() && rowBytes >= static_cast<long>(width) * 4 && rowBytes % 4 == 0) {
            ensureTexture(width, height);
            UnpackStateGuard guard;
            glPixelStorei(GL_UNPACK_ROW_LENGTH, static_cast<GLint>(rowBytes / 4));
            glBindTexture(GL_TEXTURE_2D, m_texture);
            glTexSubImage2D(GL_TEXTURE_2D, 0, 0, 0, width, height, GL_BGRA, GL_UNSIGNED_BYTE, bytes.data());
            m_flipY = true; // top-down rows
            uploaded = true;
        }
    }
    bgra->Release();
    return uploaded;
}

void BlackmagicCaptureBackend::closeCapture() {
    m_callbacksEnabled.store(false);
    if (m_input) {
        m_input->StopStreams();
        m_input->SetCallback(nullptr);
        m_input->DisableVideoInput();
        if (m_audioEnabled)
            m_input->DisableAudioInput();
        safeRelease(m_input);
    }
    safeRelease(m_callback);
    releasePendingFrame();
    // After the input has stopped and the last frame is released: unpins the capture buffers.
    m_directGpu.reset();
    m_directGpuFailed = false;
    safeRelease(m_converter);
    {
        std::lock_guard<std::mutex> lock(m_formatMutex);
        m_formatChanged = false;
    }

    if (m_texture != 0) {
        glDeleteTextures(1, &m_texture);
        m_texture = 0;
        m_texWidth = 0;
        m_texHeight = 0;
    }
    if (m_gpuConversion) {
        m_gpuConversion->cleanup();
        m_gpuConversion.reset();
    }
    m_gpuConversionFailed = false;
    m_audioEnabled = false;
    m_displayMode = 0;
    m_rgb = false;
    m_textureId = 0;
    m_width = 0;
    m_height = 0;
    m_hasSignal.store(false);
    m_transfer.store(Transfer::None);

    if (m_comInitialized) {
        CoUninitialize();
        m_comInitialized = false;
    }
}

void BlackmagicCaptureBackend::close() {
    closeCapture();
    std::lock_guard<std::mutex> lock(m_audioMutex);
    m_audio.reset();
}

void BlackmagicCaptureBackend::stopCallbacks() {
    m_callbacksEnabled.store(false);
    if (m_input)
        m_input->StopStreams();
}

void BlackmagicCaptureBackend::updateAudio(bool wanted, float volume, bool reportLevels, bool mixToOutput,
                                           const cplay::audio::SpatialSource& source) {
    if (!m_source.audio || !wanted)
        return;
    std::lock_guard<std::mutex> lock(m_audioMutex);
    if (!m_audio)
        m_audio = std::make_unique<BlackmagicAudioCapture>(m_source.input);
    m_audio->setMixToOutput(mixToOutput);
    m_audio->mixer().setSource(source);
    m_audio->keepAlive(volume, reportLevels);
}

void BlackmagicCaptureBackend::restartAudio() {
    std::lock_guard<std::mutex> lock(m_audioMutex);
    if (m_audio)
        m_audio->restart();
}

float BlackmagicCaptureBackend::takeAudioPeak() {
    std::lock_guard<std::mutex> lock(m_audioMutex);
    return m_audio ? m_audio->takePeak() : -1.f;
}

bool BlackmagicCaptureBackend::audioRunning() const {
    std::lock_guard<std::mutex> lock(m_audioMutex);
    return m_audio && m_audio->running();
}

