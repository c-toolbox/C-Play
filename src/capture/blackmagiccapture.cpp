// COM for the calling thread. RPC_E_CHANGED_MODE: already initialized (e.g. as STA by Qt), which
// the DeckLink objects (free threaded) are fine with; only a successful call is balanced.
struct ScopedCom {
    HRESULT hr;
    ScopedCom()
        : hr(CoInitializeEx(nullptr, COINIT_MULTITHREADED)) {
    }
    ~ScopedCom() {
        if (SUCCEEDED(hr))
            CoUninitialize();
    }
};

template <typename T>
void safeRelease(T*& p) {
    if (p) {
        p->Release();
        p = nullptr;
    }
}

std::string bstrToUtf8(BSTR str) {
    if (!str)
        return {};
    const int len = WideCharToMultiByte(CP_UTF8, 0, str, -1, nullptr, 0, nullptr, nullptr);
    std::string out(len > 1 ? static_cast<size_t>(len - 1) : 0, '\0');
    if (len > 1)
        WideCharToMultiByte(CP_UTF8, 0, str, -1, out.data(), len, nullptr, nullptr);
    SysFreeString(str);
    return out;
}

// Calls fn(input, device) for each DeckLink device (sub-device) that can capture, in driver
// order; input is 1-based. fn returns false to stop. COM must be initialized on this thread.
template <typename Fn>
bool forEachCaptureDevice(Fn fn) {
    IDeckLinkIterator* iterator = nullptr;
    if (FAILED(CoCreateInstance(CLSID_CDeckLinkIterator, nullptr, CLSCTX_ALL, IID_IDeckLinkIterator,
                                reinterpret_cast<void**>(&iterator))) || !iterator)
        return false;

    int input = 0;
    IDeckLink* device = nullptr;
    bool more = true;
    while (more && iterator->Next(&device) == S_OK) {
        IDeckLinkProfileAttributes* attributes = nullptr;
        LONGLONG io = 0;
        if (device->QueryInterface(IID_IDeckLinkProfileAttributes, reinterpret_cast<void**>(&attributes)) == S_OK
            && attributes->GetInt(BMDDeckLinkVideoIOSupport, &io) == S_OK && (io & bmdDeviceSupportsCapture))
            more = fn(++input, device);
        safeRelease(attributes);
        safeRelease(device);
    }
    iterator->Release();
    return true;
}

std::string deviceName(IDeckLink* device) {
    IDeckLinkProfileAttributes* attributes = nullptr;
    std::string name;
    if (device->QueryInterface(IID_IDeckLinkProfileAttributes, reinterpret_cast<void**>(&attributes)) == S_OK) {
        BSTR str = nullptr;
        if (attributes->GetString(BMDDeckLinkDisplayName, &str) == S_OK)
            name = bstrToUtf8(str);
        attributes->Release();
    }
    return name;
}

// The signal on the device's input, from the driver status (no capture needed).
struct DetectedSignal {
    bool locked = false;
    BMDDisplayMode mode = bmdModeUnknown;
    bool rgb = false;
};

DetectedSignal detectSignal(IDeckLink* device) {
    DetectedSignal signal;
    IDeckLinkStatus* status = nullptr;
    if (device->QueryInterface(IID_IDeckLinkStatus, reinterpret_cast<void**>(&status)) != S_OK)
        return signal;
    BOOL locked = FALSE;
    LONGLONG mode = 0;
    LONGLONG flags = 0;
    if (status->GetFlag(bmdDeckLinkStatusVideoInputSignalLocked, &locked) == S_OK && locked
        && status->GetInt(bmdDeckLinkStatusDetectedVideoInputMode, &mode) == S_OK
        && static_cast<BMDDisplayMode>(mode) != bmdModeUnknown) {
        signal.locked = true;
        signal.mode = static_cast<BMDDisplayMode>(mode);
        if (status->GetInt(bmdDeckLinkStatusDetectedVideoInputFormatFlags, &flags) == S_OK)
            signal.rgb = (flags & bmdDetectedVideoInputRGB444) != 0;
    }
    status->Release();
    return signal;
}

